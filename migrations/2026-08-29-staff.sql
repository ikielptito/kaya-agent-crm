-- Anyone already allowed to file tickets keeps that right: carry the old
-- allowlist across so nobody loses access the moment isReporter starts
-- reading this table first.
--
-- Numbers are normalised on the way in, matching normalizeWa in lib/staff.js
-- and the portal's normalizeWaNumber: a number stored as "0813…" would match
-- nothing, because the webhook always reports the full international form.
with cleaned as (
  select regexp_replace(wa_num, '[^0-9]', '', 'g') as d, name, role, active
  from maintenance_reporters
)
insert into staff (name, wa_num, roles, pay_type, can_report, active)
select coalesce(c.name, 'Unknown'),
       case
         when c.d like '620%'              then '62' || substr(c.d, 4)
         when c.d like '0%'                then '62' || substr(c.d, 2)
         when c.d ~ '^8[12379][0-9]{8,10}$' then '62' || c.d
         else c.d
       end,
       case when c.role = 'manager' then '{manager}'::text[] else '{}'::text[] end,
       'salaried', true, c.active
from cleaned c
where c.d <> ''
on conflict (wa_num) do nothing;
