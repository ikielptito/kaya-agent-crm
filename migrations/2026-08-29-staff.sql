-- Staff registry: the people who look after the villas.
-- RUN IN THE SUPABASE SQL EDITOR BEFORE DEPLOYING.
--
-- Until now the only record of a team member was maintenance_reporters: a
-- flat allowlist of WhatsApp numbers with no idea which villas anyone
-- covers. That was enough to decide "may this number file a ticket?" and
-- nothing else. Tukang dispatch needs to know who fixes aircon, housekeeping
-- needs to know whose villa is being cleaned, and payroll needs to know who
-- is on a monthly salary. All three want the same table, so it is built once
-- here and maintenance_reporters becomes a fallback.
--
-- Two shapes the real roster forced:
--   roles is an ARRAY. Dian is the pool man on a monthly salary and also the
--   person called for plumbing, small electrical and paint touch-ups, so he
--   belongs in the pool rota and the tukang dropdown at the same time.
--
--   pay_type separates employees from vendors. Salaried people appear on
--   Era's monthly salary sheet and flow through payroll. Per-job vendors
--   (BTC Electric) never do: their invoices are maintenance costs that reach
--   owners as statement expenses. Treating a vendor as staff would bill the
--   same repair twice.

create table if not exists staff (
  id           bigint generated by default as identity primary key,
  name         text not null,
  wa_num       text not null unique,          -- digits only, matched by the webhook
  roles        text[] not null default '{}',  -- manager|housekeeper|pool|gardener|tukang
  trades       text[] not null default '{}',  -- aircon|electrical|plumbing|carpentry|pool|paint|general
  slugs        text[] not null default '{}',  -- catalog slugs covered; empty = island-wide
  pay_type     text default 'salaried',       -- salaried | per_job
  monthly_rate numeric,                       -- salaried only, for the payroll cross-check
  can_report   boolean not null default true, -- may file maintenance items by messaging Maya
  active       boolean not null default true,
  notes        text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists staff_active_idx on staff(active) where active;
create index if not exists staff_roles_idx  on staff using gin(roles);
create index if not exists staff_slugs_idx  on staff using gin(slugs);

